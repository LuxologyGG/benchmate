import { computeCfu } from "@/lib/tools/cfu";
import type { CourseLabResult } from "./types";
import { fmt } from "./units";

export interface CfuInput {
  colonyCount: number;
  platedVolumeMl: number;
  /** e.g. 1e-4 for the 10^-4 tube */
  dilution: number;
}

export function cfuWithRange(input: CfuInput) {
  const r = computeCfu({ colonyCount: input.colonyCount, platedVolumeMl: input.platedVolumeMl, dilutionFactor: input.dilution });
  const countable = input.colonyCount >= 30 && input.colonyCount <= 300;
  const note = countable
    ? "Within the 30–300 countable range."
    : input.colonyCount < 30
      ? "Below 30 colonies: report as TFTC (too few to count) or use a less dilute plate."
      : "Above 300 colonies: report as TNTC (too numerous to count) or use a more dilute plate.";
  return { ...r, countable, note };
}

export function buildReport(r: CourseLabResult, opts: { title: string; cfu?: CfuInput; acknowledged: boolean }): string {
  const lines: string[] = [];
  const errors = r.deviations.filter((d) => d.severity === "error");
  const warns = r.deviations.filter((d) => d.severity === "warning");
  lines.push(`# ${opts.title}`, "");
  lines.push(`Generated by BenchMate Course Lab on ${new Date().toLocaleString()} · run mode: **${r.mode}**`, "");
  if (errors.length) {
    lines.push(`> **${errors.length} protocol deviation(s) flagged before export.** Student acknowledged: ${opts.acknowledged ? "yes" : "no"}.`, "");
  }
  lines.push("## Deviations", "");
  if (!r.deviations.length) lines.push("None found. Every protocol value matched the notebook within tolerance.", "");
  for (const d of [...errors, ...warns, ...r.deviations.filter((x) => x.severity === "info")]) {
    lines.push(`- **[${d.severity.toUpperCase()}] ${d.title}.** ${d.message}${d.suggestion ? ` _Fix:_ ${d.suggestion}` : ""} \`[tool: ${d.tool}]\``);
  }
  lines.push("", "## Protocol vs notebook", "", "| Step | Quantity | Protocol | Notebook | Ratio | Status | Source of number |", "| --- | --- | --- | --- | --- | --- | --- |");
  for (const c of r.comparisons) {
    lines.push(
      `| ${c.stepN} | ${c.name} | ${fmt(c.expected.value, c.expected.unit)} | ${c.observed ? fmt(c.observed.value, c.observed.unit) : "—"} | ${c.ratio === null ? "—" : c.ratio.toPrecision(3)} | ${c.status} | ${c.tool} |`,
    );
  }
  if (opts.cfu) {
    const c = cfuWithRange(opts.cfu);
    lines.push("", "## Plate count", "", `- CFU/mL = **${c.cfuPerMl.toExponential(2)}** \`[tool: compute_cfu: ${c.formula}]\``, `- ${c.note} \`[tool: countable_range 30–300]\``);
  }
  lines.push("", "## Protocol steps (extracted)", "");
  for (const s of r.steps) lines.push(`${s.n}. ${s.text}`);
  if (r.notebookTranscript) lines.push("", "## Notebook photo transcript (model output, unverified)", "", "```", r.notebookTranscript, "```");
  lines.push("", "## How these numbers were produced", "");
  lines.push("- Models only **located** values in the manual and notebook. Every located number had to appear verbatim in its source text (`provenance_check`) or it was discarded.");
  lines.push("- All ratios, concentrations and CFU values were computed by deterministic TypeScript tools named next to each number. No model arithmetic.");
  for (const l of r.ledger) lines.push(`- Model call: ${l.provider} \`${l.model}\` for ${l.purpose}: ${l.promptTokens}+${l.completionTokens} tokens, ${l.ms} ms.`);
  lines.push("", "_Not a medical device. For teaching-lab use; your TA's judgement wins._");
  return lines.join("\n");
}
