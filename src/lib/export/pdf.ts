import { jsPDF } from "jspdf";
import type { AgentResult, LabReport } from "@/lib/types";

export function buildPdfBlob(
  report: LabReport,
  agent?: AgentResult,
): Blob {
  const doc = new jsPDF({ unit: "pt", format: "letter" });
  const margin = 56;
  const pageWidth = doc.internal.pageSize.getWidth();
  const maxWidth = pageWidth - margin * 2;
  let y = margin;

  const ensureSpace = (needed: number) => {
    if (y + needed > doc.internal.pageSize.getHeight() - margin) {
      doc.addPage();
      y = margin;
    }
  };

  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  const titleLines = doc.splitTextToSize(report.title, maxWidth);
  ensureSpace(titleLines.length * 20);
  doc.text(titleLines, margin, y);
  y += titleLines.length * 20 + 8;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(100);
  doc.text("Generated by BenchMate · Meta Global AI Developer Hackathon", margin, y);
  y += 18;
  doc.setTextColor(0);

  const order: Array<[string, string]> = [
    ["Introduction", report.sections.introduction],
    ["Methods", report.sections.methods],
    ["Data", report.sections.data],
    ["Calculations", report.sections.calculations],
    ["Results", report.sections.results],
    ["Error Analysis", report.sections.errorAnalysis],
    ["Conclusion", report.sections.conclusion],
  ];

  for (const [heading, body] of order) {
    ensureSpace(36);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(12);
    doc.text(heading, margin, y);
    y += 16;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10);
    const clean = body.replace(/\*\*/g, "").replace(/`/g, "").replace(/_/g, "");
    const lines = doc.splitTextToSize(clean, maxWidth);
    for (const line of lines) {
      ensureSpace(14);
      doc.text(line, margin, y);
      y += 13;
    }
    y += 10;
  }

  if (agent?.computed?.length) {
    ensureSpace(40);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(12);
    doc.text("Tool citations", margin, y);
    y += 16;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    for (const c of agent.computed) {
      const line = `${c.label}: ${c.value} ${c.unit} ← ${c.citation.toolName}`;
      const wrapped = doc.splitTextToSize(line, maxWidth);
      for (const w of wrapped) {
        ensureSpace(12);
        doc.text(w, margin, y);
        y += 11;
      }
    }
  }

  return doc.output("blob");
}
